package com.meetback.dev.repository;

import com.meetback.dev.domain.Feed;
import org.apache.ibatis.annotations.Mapper;
import org.apache.ibatis.annotations.Param;

import java.util.List;

@Mapper
public interface FeedMapper {

    // ============================================================
    // 피드 등록
    // ============================================================

    int insert(
            Feed feed
    );


    // ============================================================
    // 피드 단건 조회
    // ============================================================

    Feed findById(
            @Param("feedId")
            Long feedId
    );


    // ============================================================
    // 기존 전체 조회
    // ============================================================

    List<Feed> findAll();


    // ============================================================
    // 피드 페이징 조회
    // ============================================================

    List<Feed> findPage(
            @Param("offset")
            int offset,

            @Param("size")
            int size
    );


    // ============================================================
    // 전체 피드 개수
    //
    // MySQL COUNT(*) 결과는 Long으로 처리
    // ============================================================

    long countAll();


    // ============================================================
    // 피드 수정
    // ============================================================

    int update(
            Feed feed
    );


    // ============================================================
    // 피드 Soft Delete
    // ============================================================

    int softDelete(
            @Param("feedId")
            Long feedId,

            @Param("userId")
            Long userId
    );
}